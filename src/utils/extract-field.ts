// ---------------------------------------------------------------------------
// Толерантное извлечение строкового поля из «сырого» объекта ELMA.
// Объекты ELMA могут иметь разные варианты именования полей
// (__id/id/Id, __name/name/Name и т.д.), поэтому функция перебирает
// предложенные кандидаты и возвращает первое найденное не-пустое значение.
// ---------------------------------------------------------------------------

/**
 * Толерантно извлечь строковое значение из объекта.
 * Перебирает `keys` по порядку, возвращает первое не-пустое строковое значение.
 * Если ничего не найдено — возвращает пустую строку.
 *
 * @example
 * extractField(raw, ['id', 'Id', '__id'])
 * extractField(raw, ['title', 'Title', 'subject', '__name'])
 */
export function extractField(
  obj: Record<string, unknown>,
  keys: string[],
): string {
  for (const k of keys) {
    const v = obj[k];
    if (typeof v === 'string' && v) {
      return v;
    }
  }
  return '';
}
